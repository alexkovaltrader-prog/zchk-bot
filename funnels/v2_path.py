def caption(index: int) -> str:
    step = STEPS[index]
    parts = [f"Шаг {index + 1} из {len(STEPS)}", step["title"], step["text"]]
    return "\n\n".join(parts)


LINK_URLS = {
    "cft": "CFT_URL",
    "reviews": "REVIEWS_URL",
    "full": "FULL_ACCESS_URL",
    "quick": "QUICK_START_URL",
    "manager": "MANAGER_URL",
    "register": "PLATFORM_URL",
}


def destination_url(button_id: str) -> str:
    import config as cfg

    attr = LINK_URLS.get(button_id)
    return getattr(cfg, attr) if attr else ""


UTM_CONTENT = {
    "cft": "prop",
    "reviews": "result",
    "full": "future_full",
    "quick": "future_quick",
    "manager": "future",
    "register": "future_register",
}


def tracked_url(button_id: str, step_id: str | None = None) -> str:
    from config import with_funnel_utm

    content = UTM_CONTENT.get(button_id) or step_id or button_id
    return with_funnel_utm(destination_url(button_id), content)


def _link_button(text: str, button_id: str, step_id: str | None = None):
    from telegram import InlineKeyboardButton
    from config import callback_query_can_open

    url = tracked_url(button_id, step_id)
    # Deep link менеджера — обычная URL-кнопка, чтобы сработал /start без гейта.
    if button_id == "manager" or not callback_query_can_open(url):
        return InlineKeyboardButton(text, url=url)
    return InlineKeyboardButton(text, callback_data=f"funnel:clk:{button_id}")


def keyboard(index: int):
    from telegram import InlineKeyboardButton, InlineKeyboardMarkup
    from config import BTN_BACK, BTN_NEXT

    step = STEPS[index]
    step_id = step["id"]
    layout = step.get("layout") or "nav"
    last = index == len(STEPS) - 1
    rows = []

    if layout == "prop":
        rows.append([_link_button("Забрать условия CFT", "cft", step_id)])
    elif layout == "result":
        rows.append([_link_button("Читать отзывы", "reviews", step_id)])
    elif layout == "future":
        rows.append([_link_button("Регистрация в Академию", "register", step_id)])
        rows.append([_link_button("Полный доступ", "full", step_id)])
        rows.append([_link_button("Быстрый старт — 59$", "quick", step_id)])
        rows.append([_link_button("У меня вопрос", "manager", step_id)])

    nav = []
    if index > 0:
        nav.append(InlineKeyboardButton(BTN_BACK, callback_data="onb:prev"))
    if not last:
        nav.append(InlineKeyboardButton(BTN_NEXT, callback_data="onb:next"))
    if nav:
        rows.append(nav)
    return InlineKeyboardMarkup(rows)
