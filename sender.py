# ── Telegram sender ──────────────────────────────────────────────────────────

async def send_telegram(telegram_id: int, text: str, keyboard=None):
    body = {
        "chat_id": telegram_id,
        "text": text,
        "parse_mode": "Markdown",
    }
    if keyboard:
        body["reply_markup"] = {"inline_keyboard": keyboard}

    async with httpx.AsyncClient(timeout=15) as client:
        resp = await client.post(
            f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage",
            json=body
        )
        if resp.status_code != 200:
            logging.error(f"Telegram send failed {telegram_id}: {resp.text}")
            return False
        return True


async def send_photo_telegram(telegram_id: int, photo_url: str) -> bool:
    try:
        async with httpx.AsyncClient(timeout=10) as client:
            photo_resp = await client.get(photo_url)
            if photo_resp.status_code != 200:
                logging.warning(f"Photo download failed {photo_url}: {photo_resp.status_code}")
                return False
            files = {"photo": ("photo.jpg", photo_resp.content, "image/jpeg")}
            resp = await client.post(
                f"https://api.telegram.org/bot{BOT_TOKEN}/sendPhoto",
                data={"chat_id": telegram_id},
                files=files
            )
            if resp.status_code != 200:
                logging.error(f"sendPhoto failed {telegram_id}: {resp.status_code} {resp.text}")
                return False
            return True
    except Exception as e:
        logging.warning(f"send_photo_telegram failed, skipping: {e}")
        return False


